export function paintExtraHead(r, style, hair, team, ink) {
  const design = EXTRA_HEAD_STYLES[style];
  if (!design) return;
  const highlight =
    '#' +
    hair
      .slice(1)
      .match(/../g)
      .map((v) =>
        Math.min(255, parseInt(v, 16) + 32)
          .toString(16)
          .padStart(2, '0'),
      )
      .join('');
  const palette = {
    H: hair,
    J: highlight,
    C: team.color,
    D: team.dark,
    L: team.light,
    A: '#fff3d4',
    I: ink,
  };
  for (const [x, y, w, h, color] of design.pixels) r(x, y, w, h, palette[color] || color);
}
